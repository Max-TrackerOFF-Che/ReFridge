export const CATEGORY_EMOJI = {
  dairy: "🥛",
  meat: "🍖",
  veg: "🥕",
  fruit: "🍎",
  grain: "🍞",
  frozen: "🧊",
  other: "📦",
};

function clean(name) {
  return name.trim().toLowerCase().replace(/[’ʼ`]/g, "'");
}

/** Повертає { emoji, category } для відомого продукту або null. */
export function guessProduct(name) {
  const n = clean(name);
  if (!n) return null;
  for (const [keys, emoji, category] of PRODUCTS) {
    if (keys.some((k) => n.includes(k))) return { emoji, category };
  }
  return null;
}

/** Емодзі для продукту: за назвою, інакше — за полицею. */
export function productEmoji(item) {
  return guessProduct(item.name)?.emoji ?? CATEGORY_EMOJI[item.category] ?? CATEGORY_EMOJI.other;
}
